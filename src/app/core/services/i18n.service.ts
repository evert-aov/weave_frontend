/**
 * Servicio de Internacionalización (i18n).
 * Permite alternar de forma reactiva entre Español e Inglés sin recargar la aplicación.
 */
@Injectable({
  providedIn: 'root',
})
export class I18nService {
  private readonly defaultLang: Language = this.readLanguage();

  readonly currentLang = signal<Language>(this.defaultLang);

  /**
   * Obtiene la traducción para una clave dada, con soporte opcional para interpolación de parámetros.
   */
  t(key: string, params?: Record<string, string | number>): string {
    const lang: Language = this.currentLang();
    const table = TRANSLATIONS[lang] || TRANSLATIONS.es;
    let text = table[key] ?? TRANSLATIONS.es[key] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return text;
  }

  /**
   * Cambia el idioma activo y guarda la preferencia en localStorage.
   */
  setLanguage(lang: Language): void {
    this.currentLang.set(lang);
    try {
      localStorage.setItem('weave_lang', lang);
    } catch {
      // La interfaz sigue funcionando si el almacenamiento local está deshabilitado.
    }
  }

  /**
   * Alterna entre Español e Inglés.
   */
  toggleLanguage(): void {
    const nextLang = this.currentLang() === 'es' ? 'en' : 'es';
    this.setLanguage(nextLang);
  }

  private readLanguage(): Language {
    try {
      return localStorage.getItem('weave_lang') === 'en' ? 'en' : 'es';
    } catch {
      return 'es';
    }
  }
}
